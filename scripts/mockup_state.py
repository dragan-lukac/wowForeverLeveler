#!/usr/bin/env python3
"""
Characters' live state from the addon save file -> personal/mockup_state.js, so mockups.html can draw the addon window
as each of them sees it: level, zone, quests in the log (and which are complete), done quests, professions, rested
XP, and the team (every character of the realm, one save per name).
Run: python3 scripts/mockup_state.py [first name ...]   (default: the highest, a middle and the lowest level one)
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from quest_report import load_saved_variables  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def newest_per_name(chars, realm):
    """One save per character name on the realm: the newest (old saves had no GUID in the key)."""
    best = {}
    for key, o in chars.items():
        if o.get('realm') == realm and o.get('name'):
            b = best.get(o['name'])
            if not b or (o.get('lastUpdated') or 0) > (b[1].get('lastUpdated') or 0):
                best[o['name']] = (key, o)
    return best


def state_of(key, c, logs):
    log = logs.get(key) or {}
    journey = log.get('journey') or []
    done_ids = set(c.get('completedQuests') or [])
    # "accepted" keeps quests that were abandoned; drop the ones done since, keep the newest 20 (the log's size).
    in_log = sorted(int(q) for q in (log.get('accepted') or {}) if int(q) not in done_ids)[-20:]
    complete = sorted({e['id'] for e in journey if e.get('k') == 'done' and e['id'] in in_log})
    zone = next((e.get('zone') for e in reversed(journey) if e.get('zone')), '')
    if not zone:
        # Older characters have no journey: the zone of their last hand-in.
        done = log.get('done') or []
        zone = done[-1].get('turnInZone', '') if done else ''
    return {'name': c.get('name'), 'class': c.get('class'), 'level': c.get('level'), 'zone': zone,
            'inLog': in_log, 'complete': complete, 'done': c.get('completedQuests') or [],
            'skills': {p['name']: {'rank': p.get('rank'), 'max': p.get('maxRank')} for p in c.get('professions') or []},
            'restedXp': c.get('restedXp') or 0, 'maxXp': c.get('maxXp') or 0, 'resting': c.get('resting'),
            'lastUpdated': c.get('lastUpdated')}


def main():
    sv = load_saved_variables()
    chars = sv['WoWForeverLevelerDB']
    logs = sv['WoWForeverLevelerQuestLog']
    realm = max(chars.values(), key=lambda c: c.get('lastUpdated') or 0).get('realm')
    team = newest_per_name(chars, realm)
    from team import load_guide
    planned = {c['name'] for c in load_guide()['characters']}
    names = sys.argv[1:]
    if not names:
        # The highest, a middle and the lowest level character of the plan (test characters left out).
        mine = sorted((o for _, o in team.values() if o['name'] in planned), key=lambda o: o.get('level') or 0)
        names = [mine[-1]['name'], mine[len(mine) // 2]['name'], mine[0]['name']] if len(mine) >= 3 else [o['name'] for o in mine]
    states = [state_of(*team[n], logs) for n in names if n in team]
    out = {'chars': states, 'team': [state_of(k, o, logs) for k, o in team.values() if o['name'] in planned]}
    os.makedirs(os.path.join(ROOT, 'personal'), exist_ok=True)
    with open(os.path.join(ROOT, 'personal', 'mockup_state.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/mockup_state.py from the addon save file. Do not edit by hand.\n')
        f.write('window.MOCKUP_STATE = ' + json.dumps(out) + ';\n')
    for s in states:
        print(f"{s['name']} ({s['class']}) level {s['level']} in {s['zone']}: {len(s['inLog'])} in log, "
              f"{len(s['done'])} done, skills {s['skills']}")
    print('team:', [t['name'] for t in out['team']])


if __name__ == '__main__':
    main()
