#!/usr/bin/env python3
"""
Compares real play (WoWForeverLevelerQuestLog from the in-game addon) with data/guide.json.
Writes personal/quest_report.md: per character and zone, quests done and level range vs. the guide.
"""

import os
import glob
import json
import time
from collections import defaultdict

from build_roster import WOW_ROOTS, parse_saved_variables

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GUIDE = os.path.join(ROOT, 'data', 'guide.json')
REPORT = os.path.join(ROOT, 'personal', 'quest_report.md')


def load_saved_variables():
    merged = {"WoWForeverLevelerDB": {}, "WoWForeverLevelerQuestLog": {}}
    for root in WOW_ROOTS:
        for path in glob.glob(os.path.join(root, "_*_", "WTF/Account/*/SavedVariables/WoWForeverLeveler.lua")):
            with open(path, 'r', encoding='utf-8') as f:
                data = parse_saved_variables(f.read())
            for var in merged:
                merged[var].update(data.get(var) or {})
    return merged


def zone_range(levels):
    """(low, high), or None when the level range is not known yet ("?")."""
    parts = levels.split('-')
    if len(parts) != 2 or not all(p.isdigit() for p in parts):
        return None
    return int(parts[0]), int(parts[1])


def journey_lines(log):
    """The character's path (addon 3.8.0+): one line per zone visit with the levels there, the
    level-ups and the quests taken and finished in it."""
    journey = log.get("journey") or []
    if not journey:
        return []
    done_at = defaultdict(int)
    for q in log.get("done") or []:
        done_at[q.get("turnInZone") or "?"] += 1
    visits = []
    for e in journey:
        # A new visit when the zone changes in any entry (the game does not always send a zone event back).
        if not visits or (e.get("zone") and e.get("zone") != visits[-1]["zone"]):
            visits.append({"zone": e.get("zone") or "?", "start": e.get("t"), "from": e.get("level"), "to": e.get("level"),
                           "ups": [], "taken": []})
        v = visits[-1]
        v["to"] = max(v["to"] or 0, e.get("level") or 0)
        if e.get("k") == "level":
            v["ups"].append(str(e.get("level")))
        if e.get("k") == "accept":
            v["taken"].append(e.get("title") or f"Quest {e.get('id')}")
    out = ["### Journey (zones in the order you visited them)", ""]
    for v in visits:
        when = time.strftime("%m-%d %H:%M", time.localtime(v["start"])) if v["start"] else "?"
        lv = f"level {v['from']}" + (f"-{v['to']}" if v["to"] != v["from"] else "")
        ups = f", level-ups: {', '.join(v['ups'])}" if v["ups"] else ""
        taken = f", took {len(v['taken'])}: {', '.join(v['taken'][:6])}{' ...' if len(v['taken']) > 6 else ''}" if v["taken"] else ""
        out.append(f"- {when} **{v['zone']}** ({lv}{ups}{taken})")
    return out + [""]


def build():
    from team import load_guide
    guide = load_guide()
    by_class = {c['class'].upper(): c for c in guide['characters']}
    sv = load_saved_variables()

    out = ["<!-- Generated by scripts/quest_report.py from the addon quest log. -->",
           "# Quest Log vs. Guide", ""]
    found = False
    for char_key, log in sv["WoWForeverLevelerQuestLog"].items():
        done = log.get("done") or []
        if not done:
            continue
        found = True
        info = sv["WoWForeverLevelerDB"].get(char_key, {})
        plan = by_class.get(str(info.get("class", "")).upper())
        route = plan['zones'] if plan else []
        out += [f"## {char_key} ({info.get('race', '?')} {str(info.get('class', '?')).title()}, level {info.get('level', '?')})", "",
                "| Zone | Quests | Your levels | Guide levels | Notes |", "| :--- | ---: | :--- | :--- | :--- |"]

        per_zone = defaultdict(list)
        for q in done:
            per_zone[q.get("acceptZone") or q.get("turnInZone") or "Unknown"].append(q)

        for zone, quests in sorted(per_zone.items(), key=lambda kv: min(q.get("level", 0) for q in kv[1])):
            levels = [q.get("level", 0) for q in quests]
            notes, guide_levels = [], "—"
            zinfo = guide['zones'].get(zone)
            if zinfo:
                guide_levels = zinfo['levels']
                rng = zone_range(zinfo['levels'])
                if rng and (min(levels) < rng[0] or max(levels) > rng[1]):
                    notes.append("outside guide range")
                skip_names = [s['quest'].lower() for s in zinfo.get('skips', [])]
                hit = [q['title'] for q in quests if any(q.get('title', '').lower() in s or s in q.get('title', '').lower() for s in skip_names)]
                if hit:
                    notes.append("did skip-listed: " + ", ".join(sorted(set(hit))))
            else:
                notes.append("zone not in guide")
            if plan and zone not in route:
                notes.append("not on this route")
            out.append(f"| {zone} | {len(quests)} | {min(levels)}–{max(levels)} | {guide_levels} | {'; '.join(notes)} |")
        out.append("")
        out += journey_lines(log)

    if not found:
        out.append("No quests logged yet. Play with addon version 1.2.0+, log out, then run `make quests`.")

    with open(REPORT, 'w', encoding='utf-8') as f:
        f.write("\n".join(out) + "\n")
    print(f"[+] Quest report written to: {REPORT}")


if __name__ == "__main__":
    build()
